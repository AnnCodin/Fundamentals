// += Operator
let score = 100;
score += 100;
console.log(score);

//-+ Operator
let balance = 4000;
balance -= 400;
console.log(balance);

//*= Operator
let donation = 100;
donation *= 2;
console.log(donation);

// /= Operator
let sweets = 10;
sweets /= 10;
console.log(sweets);

// %= Operator
let pizzaSlices = 10;
pizzaSlices %= 3;
console.log(pizzaSlices);
